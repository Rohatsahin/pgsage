from __future__ import annotations

import html
import json
import re
from datetime import UTC, datetime
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path
from typing import Any

from pgsage.tune import TuneReport, VerifiedChange

SCHEMA_VERSION = 1
MAX_CELL_LENGTH = 140
MARKDOWN_SPECIALS = re.compile(r"([\[\]`*_])")


def _version() -> str:
    try:
        return version("pgsage")
    except PackageNotFoundError:
        return "unknown"


def _text(value: str | None) -> str:
    if not value:
        return ""
    flat = " ".join(value.split())
    return MARKDOWN_SPECIALS.sub(r"\\\1", html.escape(flat, quote=False))


def _cell(value: str) -> str:
    flat = " ".join(value.split())
    clipped = flat if len(flat) <= MAX_CELL_LENGTH else flat[: MAX_CELL_LENGTH - 1] + "…"
    return html.escape(clipped, quote=False).replace("|", "\\|").replace("`", "'")


def _fence(body: str, language: str = "sql") -> str:
    fence = "````" if "```" in body else "```"
    return f"{fence}{language}\n{body}\n{fence}"


def _ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f} ms"


def _speedup(change: VerifiedChange) -> str:
    speedup = change.result.speedup
    return "n/a" if speedup is None or change.result.error else f"{speedup:.1f}x"


def _verdict(change: VerifiedChange) -> str:
    result = change.result
    if result.improved:
        return "✅ proven"
    if result.error:
        return "⚠️ failed"
    if result.equivalent is False:
        return "❌ not equivalent"
    return "❌ not faster"


def change_statements(change: VerifiedChange, concurrently: bool = True) -> list[str]:
    if change.index is not None:
        return [
            change.index.create_ddl(
                change.index.suggested_name, if_not_exists=True, concurrently=concurrently
            )
            + ";"
        ]
    if change.statistics is not None:
        stats = change.statistics
        ddl = stats.ddl.replace("CREATE STATISTICS ", "CREATE STATISTICS IF NOT EXISTS ", 1)
        return [f"{ddl};", f"ANALYZE {stats.qualified_table};"]
    return []


def build_script(
    report: TuneReport, generated_at: datetime | None = None, concurrently: bool = True
) -> str | None:
    statements = [s for change in report.proven for s in change_statements(change, concurrently)]
    if not statements:
        return None
    stamp = (generated_at or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M:%S UTC")
    header = [
        f"-- Generated by pgsage {_version()} on {stamp}.",
        "-- Each statement was proven faster on the database it was measured on; review before applying.",
        "-- Statements are idempotent (IF NOT EXISTS), so re-running is safe.",
    ]
    if concurrently:
        header.append(
            "-- Index builds use CONCURRENTLY: run outside a transaction block. If a build is "
            "interrupted, drop the INVALID index it leaves behind and run it again."
        )
    return "\n".join([*header, "", *statements]) + "\n"


def _caveats(report: TuneReport) -> list[str]:
    caveats = [
        "Timings come from `EXPLAIN ANALYZE` on one database at one moment (best of three runs); "
        "results depend on the data volume, cache state and concurrent load. Re-measure on a "
        "production-like copy before relying on a speedup.",
        "Verification measures reads only. A new index also adds cost to every write and takes disk "
        "space; judge it against your write workload.",
    ]
    if any(c.index for c in report.proven):
        caveats.append(
            "Building an index on a large table takes time and I/O. The generated script uses "
            "`CREATE INDEX CONCURRENTLY` so writes are not blocked, which requires running it "
            "outside a transaction block."
        )
    if any(c.statistics for c in report.proven):
        caveats.append(
            "Extended statistics only take effect after `ANALYZE`, which the script includes. "
            "Verification itself ran `ANALYZE`, which refreshes the table's row-count estimates."
        )
    if any(c.result.kind == "rewrite" for c in report.proven):
        caveats.append(
            "A proven rewrite returns the same columns and rows as the original on this data; "
            "it is not a proof for all data. Review it, and apply it in your application code "
            "(it is not part of the SQL script)."
        )
    return caveats


def render_markdown(
    report: TuneReport, generated_at: datetime | None = None, concurrently: bool = True
) -> str:
    when = (generated_at or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M UTC")
    proven = report.proven
    failed = [c for c in report.verified if not c.result.improved]
    explanation = report.explanation
    out = ["# pgsage tuning report", ""]
    out.append(f"Generated {when} by pgsage {_version()} · {report.rounds} round(s)")
    out.append("")
    if proven:
        out.append(f"**Result:** ✅ {len(proven)} proven change(s), ❌ {len(failed)} not proven.")
    elif report.verified:
        out.append(f"**Result:** no change was proven faster ({len(failed)} tried).")
    else:
        out.append("**Result:** no change was proposed; the query looks efficient.")
    out += ["", "## Query", "", _fence(report.query.strip() or "(not recorded)")]
    out += ["", f"Baseline execution time: **{_ms(report.baseline_ms)}**"]
    if report.hotspots:
        out += ["", "| Hotspot | Relation | Self time | Estimate off by | Rows removed by filter |"]
        out += ["| --- | --- | ---: | ---: | ---: |"]
        for row in report.hotspots:
            relation = row.get("relation") or row.get("index") or ""
            removed = row.get("rows_removed_by_filter")
            off = row.get("estimate_off_by")
            out.append(
                f"| {_cell(str(row['node']))} | {_cell(str(relation))} | {_ms(row.get('self_ms'))} "
                f"| {'' if off is None else f'{off}x'} | {'' if removed is None else f'{removed:,.0f}'} |"
            )
    out += ["", "## Diagnosis", "", _text(explanation.summary), ""]
    out.append(f"**Cause:** {_text(explanation.root_cause)}")
    if explanation.evidence:
        out += ["", "Evidence:"] + [f"- {_text(line)}" for line in explanation.evidence]
    if report.verified:
        out += ["", "## Results", ""]
        out += ["| # | Kind | Change | Verdict | Before | After | Speedup |"]
        out += ["| ---: | --- | --- | --- | ---: | ---: | ---: |"]
        for number, change in enumerate(report.verified, start=1):
            result = change.result
            out.append(
                f"| {number} | {result.kind} | `{_cell(result.statement)}` | {_verdict(change)} "
                f"| {_ms(result.before.execution_ms)} | {_ms(result.after.execution_ms)} "
                f"| {_speedup(change)} |"
            )
    if proven:
        out += ["", "## Proven changes"]
        for number, change in enumerate(proven, start=1):
            result = change.result
            out += ["", f"### {number}. {result.kind}: {_text(change.description)}", ""]
            out.append(f"- Confidence: {_text(change.confidence)}")
            if change.expected_effect:
                out.append(f"- Expected effect: {_text(change.expected_effect)}")
            out += [
                "",
                _fence(result.statement),
                "",
                f"- Measured: {_ms(result.before.execution_ms)} → {_ms(result.after.execution_ms)} "
                f"({_speedup(change)}), plan cost {result.before.total_cost:.1f} → "
                f"{result.after.total_cost:.1f}.",
                f"- Plan before: {_cell(' > '.join(result.before.node_types))}",
                f"- Plan after: {_cell(' > '.join(result.after.node_types))}",
            ]
            if result.kind == "rewrite":
                out.append("- Equivalence: same columns and same rows on this data.")
        script = build_script(report, generated_at, concurrently)
        if script:
            out += [
                "",
                "## Apply",
                "",
                "Plain SQL; paste it into any migration tool or run it with `psql`.",
                "",
            ]
            out.append(_fence(script.rstrip("\n")))
    if failed:
        out += ["", "## Not proven"]
        for change in failed:
            result = change.result
            reason = (
                result.error
                or result.note
                or ("results differ" if result.equivalent is False else "not measurably faster")
            )
            extra = ""
            if result.kind == "index" and not result.error and not result.after.uses_new_index:
                extra = " The planner did not use the new index."
            out.append(f"- `{_cell(result.statement)}`: {_text(reason)}.{extra}")
    if explanation.rejected:
        out += ["", "## Model output that was ignored"]
        out += [f"- {_text(line)}" for line in explanation.rejected]
    out += ["", "## Caveats", ""] + [f"- {line}" for line in _caveats(report)]
    return "\n".join(out) + "\n"


def _change_dict(change: VerifiedChange, concurrently: bool) -> dict[str, Any]:
    result = change.result
    return {
        "kind": result.kind,
        "description": change.description,
        "confidence": change.confidence,
        "expected_effect": change.expected_effect,
        "statement": result.statement,
        "sql": change_statements(change, concurrently) if result.improved else [],
        "proven": result.improved,
        "equivalent": result.equivalent,
        "uses_new_index": result.after.uses_new_index,
        "before_ms": result.before.execution_ms,
        "after_ms": result.after.execution_ms,
        "speedup": result.speedup,
        "cost_before": result.before.total_cost,
        "cost_after": result.after.total_cost,
        "plan_before": result.before.node_types,
        "plan_after": result.after.node_types,
        "note": result.note,
        "error": result.error,
    }


def render_json(
    report: TuneReport, generated_at: datetime | None = None, concurrently: bool = True
) -> str:
    explanation = report.explanation
    payload = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": (generated_at or datetime.now(UTC)).isoformat(),
        "pgsage_version": _version(),
        "query": report.query,
        "baseline_ms": report.baseline_ms,
        "hotspots": report.hotspots,
        "rounds": report.rounds,
        "diagnosis": {
            "summary": explanation.summary,
            "root_cause": explanation.root_cause,
            "evidence": explanation.evidence,
        },
        "changes": [_change_dict(c, concurrently) for c in report.verified],
        "ignored_model_output": explanation.rejected,
        "script": build_script(report, generated_at, concurrently),
    }
    return json.dumps(payload, indent=2) + "\n"


def write_report(
    directory: Path,
    report: TuneReport,
    now: datetime | None = None,
    concurrently: bool = True,
) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    moment = now or datetime.now(UTC)
    base = f"pgsage-{moment:%Y%m%d-%H%M%S}"
    stem, attempt = base, 1
    while any(directory.glob(f"{stem}.*")):
        attempt += 1
        stem = f"{base}-{attempt}"
    files = {
        f"{stem}.md": render_markdown(report, moment, concurrently),
        f"{stem}.json": render_json(report, moment, concurrently),
    }
    script = build_script(report, moment, concurrently)
    if script:
        files[f"{stem}.sql"] = script
    written: list[Path] = []
    for name, content in files.items():
        path = directory / name
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written
